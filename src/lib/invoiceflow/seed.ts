function field(name: FieldName, value: string, confidence: number, corrected = false): ExtractedField {
  return { name, value, confidence, originalValue: value, corrected };
}

function line(id: string, description: string, qty: string, unit: number, amount: number): InvoiceLineItem {
  return { id, description, quantity: qty, unitPriceCents: unit, amountCents: amount };
}

function inv(partial: Omit<Invoice, "fingerprint" | "workspaceId" | "fields"> & { fields?: ExtractedField[] }): Invoice {
  const fields =
    partial.fields ??
    [
      field("vendor_name", partial.vendorName, 0.97),
      field("invoice_number", partial.invoiceNumber, 0.98),
      field("issue_date", partial.issueDate, 0.96),
      field("due_date", partial.dueDate, 0.95),
      field("subtotal", (partial.subtotalCents / 100).toFixed(2), 0.97),
      field("tax", (partial.taxCents / 100).toFixed(2), 0.96),
      field("total", (partial.totalCents / 100).toFixed(2), 0.98),
      field("currency", partial.currency, 0.99),
      field("po_number", partial.poNumber ?? "", 0.94),
      field("bank_account_suffix", partial.bankAccountSuffix, 0.93),
    ];
  const invoice: Invoice = {
    ...partial,
    workspaceId: WS,
    fields,
    fingerprint: "",
  };
  invoice.fingerprint = invoiceFingerprint(invoice);
  return invoice;
}

function extraction(id: string, confidence: number, raw: string, at: string): Invoice["extraction"] {
  return {
    id,
    method: "sandbox_parser",
    startedAt: at,
    completedAt: at,
    overallConfidence: confidence,
    rawText: raw,
  };
}

