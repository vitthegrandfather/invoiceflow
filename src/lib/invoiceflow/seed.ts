function rest(
  publicId: string,
  vendor: Vendor,
  status: InvoiceStatus,
  source: InvoiceSource,
  number: string,
  issue: string,
  due: string,
  sub: number,
  tax: number,
  created: string,
  extra: Partial<Invoice> = {},
): Invoice {
  const n = publicId.slice(-3);
  return inv({
    id: `inv_${n}`,
    publicId,
    vendorId: vendor.id,
    vendorName: vendor.name,
    source,
    status,
    currency: vendor.currency,
    invoiceNumber: number,
    poNumber: extra.poNumber ?? null,
    poId: extra.poId ?? null,
    issueDate: issue,
    dueDate: due,
    paymentTerms: vendor.paymentTerms,
    subtotalCents: sub,
    taxCents: tax,
    totalCents: sub + tax,
    extractionConfidence: extra.extractionConfidence ?? 0.94,
    duplicateScore: 0,
    assignedReviewer: extra.assignedReviewer ?? "Priya Shah",
    createdAt: created,
    updatedAt: extra.updatedAt ?? created,
    filename: `${number}.pdf`,
    contentType: "application/pdf",
    notes: extra.notes ?? "",
    bankAccountSuffix: vendor.bankAccountSuffix,
    lineItems: extra.lineItems ?? [line(`l${n}a`, "Professional services", "1", sub, sub)],
    issues: extra.issues ?? [],
    duplicateMatch: null,
    extraction: extra.extraction ?? extraction(`ex_${n}`, extra.extractionConfidence ?? 0.94, `${vendor.name}\nInvoice ${number}\nTotal ${(sub + tax) / 100}`, created),
    approval: extra.approval ?? null,
    varianceAcknowledged: false,
    varianceReason: null,
    providerBillId: extra.providerBillId ?? null,
    idempotencyKey: extra.idempotencyKey ?? `ing_${number.toLowerCase()}`,
    fields: extra.fields,
  });
}

